// Helper to convert any ClassroomCommandItem into a TeacherLessonItem for practice
export function convertCommandToTeacherLesson(cmd: ClassroomCommandItem): TeacherLessonItem {
  return {
    id: `cmd-lesson-${cmd.id}`,
    subject: cmd.subject || 'ClassroomGeneral',
    subjectNameVi: cmd.categoryVi,
    cefrLevel: cmd.level,
    scenario: `Khẩu lệnh sư phạm: ${cmd.meaningVi}`,
    englishPrompt: cmd.commandEn,
    phonetic: cmd.phonetic,
    vietnameseMeaning: cmd.meaningVi,
    teachingContext: cmd.situation,
    keyTerms: [cmd.categoryVi, `Chuẩn CEFR ${cmd.level}`, 'Classroom English'],
    studentReaction: 'Học sinh toàn lớp chú ý lắng nghe và lập tức thực hiện khẩu lệnh của giáo viên.',
    pedagogicalNote: `Khẩu lệnh thuộc danh mục "${cmd.categoryVi}". Thầy/Cô hãy phát âm với ngữ điệu tự tin, nhả chữ dứt khoát và biểu cảm để tạo thói quen phản xạ ngôn ngữ tự nhiên cho học sinh.`,
    emoji: cmd.icon || '📢',
  };
}

